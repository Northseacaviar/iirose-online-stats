"""热度:站点口径「房间热度」的全站合计。

站内 wiki 的「状态与热度贡献」表列出各状态标识的贡献分 —— 状态颜色每 2 分钟
刷新一次,颜色与状态码一一对应。站点算房间热度时遍历在线用户,把
`scoreJson[状态码]` 累加到该用户所在房间,再沿地图树把子节点累加到父节点;
所以「全站热度」= Σ 每个在线用户的状态分,机器人账户(状态码 `a`)不贡献。

分数表的来源有个坑:站点把它放在客户端内存里(`Assets.userStatusScoreJson`),
纯 WS 客户端拿不到,这里按站内 wiki 的表落地。真机核对办法见 app/README.md。
"""
from __future__ import annotations

# 状态码 → 热度贡献分(站内 wiki「状态与热度贡献」表)
STATUS_SCORE: dict[str, float] = {
    "9": 20.0,   # 蛙绿   聊天中 0-2 分钟
    "8": 18.0,   # 草原绿 聊天中 2-4 分钟
    "7": 16.0,   # 黄绿色 聊天中 4-6 分钟
    "6": 14.0,   # 枯草绿 聊天中 6-8 分钟
    "5": 12.0,   # 蛋黄色 聊天中 8-10 分钟
    "4": 4.0,    # 淡橘橙 窥屏中
    "3": 3.5,    # 杏黄色 窥屏中
    "2": 3.0,    # 脐橙色 窥屏中
    "1": 2.5,    # 蟹壳红 窥屏中
    "0": 2.0,    # 桂红   窥屏中
    "": 0.0,     # 淡菽红 挂机中(与机器人同为 0)
    "*": 1.0,    # 镍灰   刚进房 0-2 分钟
    "a": 0.0,    # 人工智能(认证机器人账户)
}


def score_of(status: str) -> float:
    """状态码 → 热度分;未知状态记 0(宁可少算,不猜)。"""
    return STATUS_SCORE.get(status, 0.0)
